-- Report 1: Most frequently booked routes, limited to the requested top N.
CREATE OR REPLACE PROCEDURE report_most_used_routes(
  p_top_n IN NUMBER,
  p_results OUT SYS_REFCURSOR
) IS
  e_invalid_input EXCEPTION;
  validation_message VARCHAR2(4000);
BEGIN
  IF p_top_n IS NULL OR p_top_n < 0 OR p_top_n != TRUNC(p_top_n) THEN
    validation_message := 'topN must be a non-negative whole number';
    RAISE e_invalid_input;
  END IF;

  OPEN p_results FOR
    SELECT route_id, route_code, origin, destination, booking_count
    FROM (
      SELECT r.route_id, r.route_code, r.origin, r.destination,
             COUNT(b.booking_id) AS booking_count
      FROM routes r
      LEFT JOIN trips t ON t.route_id = r.route_id
      LEFT JOIN bookings b ON b.trip_id = t.trip_id AND b.status <> 'cancelled'
      GROUP BY r.route_id, r.route_code, r.origin, r.destination
      ORDER BY booking_count DESC, r.route_code
    )
    WHERE ROWNUM <= p_top_n;
EXCEPTION
  WHEN e_invalid_input THEN
    RAISE_APPLICATION_ERROR(-20001, validation_message);
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20002, 'No route report data found');
  WHEN VALUE_ERROR THEN
    RAISE_APPLICATION_ERROR(-20003, 'Invalid value in most-used-routes report: ' || SQLERRM);
  WHEN OTHERS THEN
    log_report_error('REPORT_MOST_USED_ROUTES', SQLCODE, SQLERRM, DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    RAISE;
END;
/

-- Report 2: Total successful ticket-payment revenue between inclusive dates.
CREATE OR REPLACE PROCEDURE report_paid_revenue(
  p_from_date IN DATE,
  p_to_date IN DATE,
  p_results OUT SYS_REFCURSOR
) IS
  e_invalid_input EXCEPTION;
  validation_message VARCHAR2(4000);
BEGIN
  IF p_from_date IS NULL OR p_to_date IS NULL THEN
    validation_message := 'fromDate and toDate are required';
    RAISE e_invalid_input;
  END IF;
  IF TRUNC(p_from_date) > TRUNC(p_to_date) THEN
    validation_message := 'fromDate must not be after toDate';
    RAISE e_invalid_input;
  END IF;

  OPEN p_results FOR
    SELECT COUNT(payment_id) AS paid_payment_count,
           NVL(SUM(amount), 0) AS total_revenue
    FROM payments
    WHERE status = 'paid'
      AND payment_date >= TRUNC(p_from_date)
      AND payment_date < TRUNC(p_to_date) + 1;
EXCEPTION
  WHEN e_invalid_input THEN
    RAISE_APPLICATION_ERROR(-20011, validation_message);
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20012, 'No paid-revenue report data found');
  WHEN VALUE_ERROR THEN
    RAISE_APPLICATION_ERROR(-20013, 'Invalid value in paid-revenue report: ' || SQLERRM);
  WHEN OTHERS THEN
    log_report_error('REPORT_PAID_REVENUE', SQLCODE, SQLERRM, DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    RAISE;
END;
/

-- Report 3: Passenger travel history, newest departure first.
CREATE OR REPLACE PROCEDURE report_passenger_history(
  p_passenger_id IN NUMBER,
  p_results OUT SYS_REFCURSOR
) IS
  e_invalid_input EXCEPTION;
  validation_message VARCHAR2(4000);
BEGIN
  IF p_passenger_id IS NULL OR p_passenger_id <= 0 OR p_passenger_id != TRUNC(p_passenger_id) THEN
    validation_message := 'passengerId must be a positive whole number';
    RAISE e_invalid_input;
  END IF;

  OPEN p_results FOR
    SELECT p.passenger_id,
           p.first_name || ' ' || p.last_name AS passenger_name,
           b.booking_id,
           t.trip_id,
           t.departure_time,
           t.arrival_time,
           r.route_id,
           r.route_code,
           r.origin,
           r.destination,
           b.seat_number,
           b.status AS booking_status,
           b.amount AS booking_amount
    FROM passengers p
    JOIN bookings b ON b.passenger_id = p.passenger_id
    JOIN trips t ON t.trip_id = b.trip_id
    JOIN routes r ON r.route_id = t.route_id
    WHERE p.passenger_id = p_passenger_id
    ORDER BY t.departure_time DESC, b.booking_id DESC;
EXCEPTION
  WHEN e_invalid_input THEN
    RAISE_APPLICATION_ERROR(-20021, validation_message);
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20022, 'No passenger travel history found');
  WHEN VALUE_ERROR THEN
    RAISE_APPLICATION_ERROR(-20023, 'Invalid value in passenger-history report: ' || SQLERRM);
  WHEN OTHERS THEN
    log_report_error('REPORT_PASSENGER_HISTORY', SQLCODE, SQLERRM, DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    RAISE;
END;
/

-- Report 4: Vehicles already due or due within the requested number of days.
CREATE OR REPLACE PROCEDURE report_vehicles_due(
  p_days_ahead IN NUMBER,
  p_results OUT SYS_REFCURSOR
) IS
  e_invalid_input EXCEPTION;
  validation_message VARCHAR2(4000);
BEGIN
  IF p_days_ahead IS NULL OR p_days_ahead < 0 OR p_days_ahead != TRUNC(p_days_ahead) THEN
    validation_message := 'daysAhead must be a non-negative whole number';
    RAISE e_invalid_input;
  END IF;

  OPEN p_results FOR
    SELECT vehicle_id,
           registration_number,
           make,
           model,
           status,
           next_maintenance_date,
           TRUNC(next_maintenance_date) - TRUNC(SYSDATE) AS days_until_due
    FROM vehicles
    WHERE status = 'maintenance'
       OR (next_maintenance_date IS NOT NULL
           AND next_maintenance_date < TRUNC(SYSDATE) + p_days_ahead + 1)
    ORDER BY next_maintenance_date, registration_number;
EXCEPTION
  WHEN e_invalid_input THEN
    RAISE_APPLICATION_ERROR(-20031, validation_message);
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20032, 'No vehicles due for maintenance found');
  WHEN VALUE_ERROR THEN
    RAISE_APPLICATION_ERROR(-20033, 'Invalid value in maintenance-due report: ' || SQLERRM);
  WHEN OTHERS THEN
    log_report_error('REPORT_VEHICLES_DUE', SQLCODE, SQLERRM, DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    RAISE;
END;
/

-- Report 5: Driver performance computed from completed trips and live feedback.
CREATE OR REPLACE PROCEDURE report_driver_performance(
  p_results OUT SYS_REFCURSOR
) IS
  e_invalid_input EXCEPTION;
BEGIN
  OPEN p_results FOR
    SELECT d.driver_id,
           d.first_name,
           d.last_name,
           (SELECT COUNT(*)
            FROM trips t
            WHERE t.driver_id = d.driver_id AND t.status = 'completed') AS completed_trip_count,
           (SELECT ROUND(AVG(f.rating), 2)
            FROM feedback f
            WHERE f.driver_id = d.driver_id) AS average_rating,
           (SELECT COUNT(*)
            FROM feedback f
            WHERE f.driver_id = d.driver_id) AS feedback_count
    FROM drivers d
    ORDER BY completed_trip_count DESC, average_rating DESC NULLS LAST, d.driver_id;
EXCEPTION
  WHEN e_invalid_input THEN
    RAISE_APPLICATION_ERROR(-20041, 'Invalid driver-performance report input');
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20042, 'No driver performance data found');
  WHEN VALUE_ERROR THEN
    RAISE_APPLICATION_ERROR(-20043, 'Invalid value in driver-performance report: ' || SQLERRM);
  WHEN OTHERS THEN
    log_report_error('REPORT_DRIVER_PERFORMANCE', SQLCODE, SQLERRM, DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    RAISE;
END;
/

-- Report 6: Paid revenue per Oracle route; MongoDB review ratings are merged by Node.
CREATE OR REPLACE PROCEDURE report_route_revenue(
  p_results OUT SYS_REFCURSOR
) IS
  e_invalid_input EXCEPTION;
BEGIN
  OPEN p_results FOR
    SELECT r.route_id,
           r.route_code,
           r.origin,
           r.destination,
           NVL(SUM(CASE WHEN py.status = 'paid' THEN py.amount ELSE 0 END), 0) AS paid_revenue,
           COUNT(CASE WHEN py.status = 'paid' THEN py.payment_id END) AS paid_payment_count
    FROM routes r
    LEFT JOIN trips t ON t.route_id = r.route_id
    LEFT JOIN bookings b ON b.trip_id = t.trip_id
    LEFT JOIN payments py ON py.booking_id = b.booking_id
    GROUP BY r.route_id, r.route_code, r.origin, r.destination
    ORDER BY paid_revenue DESC, r.route_code;
EXCEPTION
  WHEN e_invalid_input THEN
    RAISE_APPLICATION_ERROR(-20051, 'Invalid route-revenue report input');
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20052, 'No route revenue data found');
  WHEN VALUE_ERROR THEN
    RAISE_APPLICATION_ERROR(-20053, 'Invalid value in route-revenue report: ' || SQLERRM);
  WHEN OTHERS THEN
    log_report_error('REPORT_ROUTE_REVENUE', SQLCODE, SQLERRM, DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    RAISE;
END;
/

