DECLARE
  table_count PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO table_count
  FROM user_tables
  WHERE table_name = 'REPORT_ERROR_LOG';

  IF table_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE report_error_log (
      error_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      procedure_name VARCHAR2(128) NOT NULL,
      error_code NUMBER NOT NULL,
      error_message VARCHAR2(4000) NOT NULL,
      error_backtrace CLOB,
      logged_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
    )';
  END IF;
END;
