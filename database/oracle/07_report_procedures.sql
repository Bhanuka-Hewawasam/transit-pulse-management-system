CREATE OR REPLACE PROCEDURE log_report_error(
  p_procedure_name IN VARCHAR2,
  p_error_code IN NUMBER,
  p_error_message IN VARCHAR2,
  p_error_backtrace IN CLOB
) IS
  PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
  INSERT INTO report_error_log (procedure_name, error_code, error_message, error_backtrace)
  VALUES (p_procedure_name, p_error_code, p_error_message, p_error_backtrace);
  COMMIT;
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
END;
